// MultiHD Launcher — Quartus Prime project-file generator (.qpf / .qsf / .sdc).
//
// Qt reference: /home/bismillah/QuestaLauncher/mainwindow.cpp:691-763
// (`MainWindow::generateQuartusFiles`). The generators are pure string builders;
// the filesystem side-effects live in `generateQuartusFiles` only.
//
// NOTE: no `vscode` import, Node builtins only (golden-tested in plain Node).
// ─────────────────────────────────────────────────────────────────────────────

import * as path from 'path';
import { chopped, ensureDir, pathExists, writeTextFile } from './util';

export interface QuartusOptions {
  /** Project directory (its basename is normally the project/revision name). */
  dir: string;
  /** Project folder name (`QDir(dir).dirName()` in Qt). */
  projectName: string;
  /** Exclusion-filtered `.sv` basenames, in `activeFiles` order (custom order NOT applied in Qt). */
  activeFiles: string[];
  /** ISO timestamp `YYYY-MM-DDTHH:MM:SS` (injected for determinism). */
  timestamp: string;
}

export interface GeneratedFile {
  path: string;
  content: string;
}

export interface GenerationResult {
  written: GeneratedFile[];
  skipped: Array<{ path: string; reason: string }>;
  dirs: string[];
  warnings: string[];
}

/**
 * Pure builder: returns the exact Qt bytes for `.qpf`, `.qsf`, `.sdc` plus the
 * detected top-level entity.
 *
 * `topEntity` = last active file that does not end in `_tb.sv`, `.sv` chopped
 * (`QString::chopped(3)`), else the last active file chopped
 * (mainwindow.cpp:710-715).
 */
export function buildQuartusContents(
  o: QuartusOptions,
): { qpf: string; qsf: string; sdc: string; topEntity: string } {
  const projName = o.projectName || path.basename(o.dir);
  const timestamp = o.timestamp;

  let topEntity = '';
  for (const f of o.activeFiles) {
    if (!f.endsWith('_tb.sv')) topEntity = chopped(f, 3);
  }
  if (topEntity === '' && o.activeFiles.length > 0) {
    topEntity = chopped(o.activeFiles[o.activeFiles.length - 1], 3);
  }

  // ── .qpf (mainwindow.cpp:697-707) — note the two spaces before the timestamp.
  const qpf = [
    '# Quartus Prime Project File',
    '# Generated by MultiHD Launcher  ' + timestamp,
    '',
    'QUARTUS_VERSION = "23.1"',
    'DATE = "' + timestamp + '"',
    '',
    'PROJECT_REVISION = "' + projName + '"',
    '',
  ].join('\n');

  // ── .qsf (mainwindow.cpp:717-735) — one SYSTEMVERILOG_FILE per active file.
  const qsfLines: string[] = [
    '# Quartus Settings File',
    '# Generated by MultiHD Launcher  ' + timestamp,
    '',
    'set_global_assignment -name FAMILY "Cyclone V"',
    'set_global_assignment -name DEVICE AUTO',
    'set_global_assignment -name TOP_LEVEL_ENTITY ' + topEntity,
    'set_global_assignment -name PROJECT_OUTPUT_DIRECTORY output_files',
    'set_global_assignment -name MIN_CORE_JUNCTION_TEMP 0',
    'set_global_assignment -name MAX_CORE_JUNCTION_TEMP 85',
    '',
  ];
  for (const sv of o.activeFiles) {
    qsfLines.push('set_global_assignment -name SYSTEMVERILOG_FILE ' + sv);
  }
  qsfLines.push('');
  qsfLines.push('set_global_assignment -name SDC_FILE ' + projName + '.sdc');
  qsfLines.push('');
  const qsf = qsfLines.join('\n');

  // ── .sdc (mainwindow.cpp:739-758) — create-once template, never overwritten.
  const sdc = [
    '# Synopsys Design Constraints (.sdc)',
    '# Generated by MultiHD Launcher  ' + timestamp,
    '# Adjust the clock period and port names to match your design.',
    '',
    '# ── Primary clock ────────────────────────────────────────────────────────',
    'create_clock -period 10.000 -name clk [get_ports clk]',
    '',
    '# ── Derive clock uncertainty automatically ───────────────────────────────',
    'derive_clock_uncertainty',
    '',
    '# ── False paths for async reset / buttons (adjust as needed) ────────────',
    '# set_false_path -from [get_ports rst_n] -to [all_registers]',
    '',
  ].join('\n');

  return { qpf, qsf, sdc, topEntity };
}

/**
 * Write `<dir>/<projectName>.qpf`, `.qsf`, `.sdc` + create `output_files/`.
 *
 * Qt parity (mainwindow.cpp:691-763):
 *  - `.qpf` / `.qsf` are always (re)written;
 *  - `.sdc` is written ONLY when it does not exist ("respect hand-edited files")
 *    and reported in `skipped` otherwise;
 *  - `output_files/` is always created (Qt logs `(created)` even if it exists).
 */
export function generateQuartusFiles(o: QuartusOptions): GenerationResult {
  const projName = o.projectName || path.basename(o.dir);
  const { qpf, qsf, sdc } = buildQuartusContents(o);

  const written: GeneratedFile[] = [];
  const skipped: Array<{ path: string; reason: string }> = [];
  const dirs: string[] = [];
  const warnings: string[] = [];

  ensureDir(o.dir);

  const qpfPath = path.join(o.dir, projName + '.qpf');
  writeTextFile(qpfPath, qpf);
  written.push({ path: qpfPath, content: qpf });

  const qsfPath = path.join(o.dir, projName + '.qsf');
  writeTextFile(qsfPath, qsf);
  written.push({ path: qsfPath, content: qsf });

  const sdcPath = path.join(o.dir, projName + '.sdc');
  if (pathExists(sdcPath)) {
    skipped.push({ path: sdcPath, reason: 'exists — not overwritten' });
  } else {
    writeTextFile(sdcPath, sdc);
    written.push({ path: sdcPath, content: sdc });
  }

  const outputDir = path.join(o.dir, 'output_files');
  ensureDir(outputDir);
  dirs.push(outputDir);

  if (o.activeFiles.length === 0) {
    warnings.push('No active .sv files — generated Quartus project has no source files.');
  }

  return { written, skipped, dirs, warnings };
}
