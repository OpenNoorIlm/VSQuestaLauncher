// ─────────────────────────────────────────────────────────────────────────────
// MultiHD Launcher — Questa FSE `run.do` generator.
//
// Qt reference: /home/bismillah/QuestaLauncher/mainwindow.cpp:624-688
// (`MainWindow::generateRunDo`). Byte-accurate for the Qt (GUI) variant, plus
// the existing VS Code extension's CLI variant (no `add wave`, trailing
// `quit -f`).
//
// NOTE: this module must stay importable from plain Node (no `vscode`, no deps
// beyond Node builtins) — the verifier golden-tests `out/tools/questa.js`.
// ─────────────────────────────────────────────────────────────────────────────

import * as path from 'path';
import { ensureDir, writeTextFile } from './util';

export interface RunDoOptions {
  /** Project directory (the folder that contains the `.sv` files). */
  dir: string;
  /** Source files, in compile order. Joined verbatim in Qt style (bare names). */
  files: string[];
  /** Test-bench / top module name (stem of `topFile`, `@topmodule` may win). */
  topModule: string;
  /**
   * Registered project libraries to compile before the project itself, in
   * `questa_libs.json` order. `workDbPath` is the absolute
   * `~/.questa_libs/work/<name>` database; `sourceFiles` are absolute `.sv`
   * paths inside the library source folder (Qt: `sourcePath + "/" + f`).
   */
  libs: Array<{ name: string; workDbPath: string; sourceFiles: string[] }>;
  /** `["-L", "<workDbPath>", ...]` from `LibraryManager.linkFlags`. */
  libFlags: string[];
  /** ISO timestamp `YYYY-MM-DDTHH:MM:SS` (passed in so output is deterministic). */
  timestamp: string;
  /** `gui` = Qt parity (`add wave -r /*`); `cli` = headless (`quit -f`). */
  mode: 'gui' | 'cli';
  /** Extension-only: user vlog args from `conf.svconf`/settings (`-reportprogress 300`). */
  extraVlogArgs?: string;
  /** Extension-only: user vsim args from `conf.svconf`. */
  vsimArgs?: string;
  /** Work library name (default `work`, Qt hard-codes it; `@work:` overrides). */
  workLib?: string;
}

/**
 * Build the exact `run.do` text.
 *
 * Qt layout (mainwindow.cpp:662-681):
 * ```
 * # Questa run script — generated by MultiHD Launcher
 * # <timestamp>
 *
 * quietly vlib work
 * vlog -work <libWorkDb> <dep sources ...>        (one per registered lib)
 * vlog -work work [-L ... ]<files ...>
 * vopt +acc [-L ... ] work.<top> -o <top>_opt
 * vsim [-L ... ] <top>_opt
 * add wave -r /*          (GUI only)
 * run -all
 * quit -f                 (CLI only — extension variant)
 * ```
 */
export function buildRunDo(opts: RunDoOptions): string {
  const workLib = (opts.workLib ?? '').trim() || 'work';
  const libFlagsStr = opts.libFlags.join(' ');
  const extraVlogArgs = (opts.extraVlogArgs ?? '').trim();
  const vsimArgs = (opts.vsimArgs ?? '').trim();
  const vlogFiles = opts.files.join(' ');

  const lines: string[] = [];
  lines.push('# Questa run script — generated by MultiHD Launcher');
  lines.push('# ' + opts.timestamp);
  lines.push('');
  lines.push('quietly vlib ' + workLib);

  // One `vlog -work <db>` line per dependency (Qt mainwindow.cpp:667-674).
  for (const lib of opts.libs) {
    lines.push('vlog -work ' + lib.workDbPath + ' ' + lib.sourceFiles.join(' '));
  }

  // Project compile line: Qt puts the `-L` flags immediately before the files;
  // the extension's extra vlog args sit right after `-work <lib>` (v1.9.1 order).
  lines.push(
    'vlog -work ' + workLib + ' ' +
    (extraVlogArgs ? extraVlogArgs + ' ' : '') +
    (libFlagsStr ? libFlagsStr + ' ' : '') +
    vlogFiles,
  );

  // `vopt +acc [<libFlags> ]<workLib>.<top> -o <top>_opt` (mainwindow.cpp:676-677).
  lines.push(
    'vopt +acc' +
    (libFlagsStr ? ' ' + libFlagsStr : '') +
    ' ' + workLib + '.' + opts.topModule +
    ' -o ' + opts.topModule + '_opt',
  );

  // `vsim [<vsimArgs> ][<libFlags> ]<top>_opt` (mainwindow.cpp:678-679).
  lines.push(
    'vsim' +
    (vsimArgs ? ' ' + vsimArgs : '') +
    (libFlagsStr ? ' ' + libFlagsStr : '') +
    ' ' + opts.topModule + '_opt',
  );

  if (opts.mode === 'gui') lines.push('add wave -r /*');
  lines.push('run -all');
  if (opts.mode === 'cli') lines.push('quit -f');

  return lines.join('\n') + '\n';
}

/**
 * Write `<dir>/run.do` (always overwritten, like Qt) and return the path +
 * generated content. Throws on I/O failure.
 */
export function writeRunDo(opts: RunDoOptions): { path: string; content: string } {
  const content = buildRunDo(opts);
  const filePath = path.join(opts.dir, 'run.do');
  ensureDir(opts.dir);
  writeTextFile(filePath, content);
  return { path: filePath, content };
}
