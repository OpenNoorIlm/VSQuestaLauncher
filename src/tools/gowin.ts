// gowincstdialog.cpp:264-267 — names that look like ports but are keywords.
const PORT_KEYWORDS = new Set([
  'module', 'endmodule', 'begin', 'end', 'if', 'else', 'always', 'assign',
  'wire', 'logic', 'reg', 'parameter', 'localparam', 'integer', 'real',
]);

/**
 * Port auto-detection with byte-for-byte Qt semantics
 * (gowincstdialog.cpp:235-275):
 *  1. strip block comments `/* … *​/` — Qt's `.` does NOT match newlines, so only
 *     single-line block comments are stripped (multi-line ones survive!);
 *  2. strip line comments `// …` (replaced by a space);
 *  3. match `(input|output|inout) [wire|logic|reg|signed|unsigned]? [width]? name [,;)]`
 *     case-insensitively, globally;
 *  4. direction lower-cased, width trimmed (keeps inner spacing, e.g. `[ 7 : 0 ]`);
 *  5. skip keyword names, de-duplicate by name keeping the first occurrence.
 */
export function parsePorts(svText: string): CstPort[] {
  const ports: CstPort[] = [];

  // NOTE: no `s` (dotAll) flag — matches Qt's default QRegularExpression behaviour.
  let text = svText.replace(/\/\*.*?\*\//g, ' ');
  text = text.replace(/\/\/[^\n]*/g, ' ');

  const portRe = new RegExp(
    '\\b(input|output|inout)\\s+(?:wire|logic|reg|signed|unsigned)?\\s*' +
    '((?:\\[\\s*[\\w\\s+\\-*:/]+\\s*:\\s*[\\w\\s+\\-*:/]+\\s*\\])?\\s*)' +
    '(\\w+)\\s*(?:[,;)])',
    'gi',
  );

  const seen = new Set<string>();
  let match: RegExpExecArray | null;
  while ((match = portRe.exec(text)) !== null) {
    const direction = match[1].toLowerCase() as CstPort['direction'];
    const width = match[2].trim();
    const name = match[3];
    if (PORT_KEYWORDS.has(name.toLowerCase())) continue;
    if (seen.has(name)) continue;
    seen.add(name);
    ports.push({ name, direction, width });
  }
  return ports;
}

/**
 * Build the Gowin `.cst` template exactly like the Qt dialog
 * (gowincstdialog.cpp:278-323): header comments, then direction groups in
 * input → output → inout order, `IO_LOC  "<name>"[ <width>]  XX ;`,
 * `IO_PORT "<name>"  PULL_MODE=NONE  DRIVE=8  IOSTD=LVCMOS33 ;`.
 */
export function buildCstTemplate(ports: CstPort[], device: string): string {
  const lines: string[] = [];
  lines.push('// Gowin Physical Constraint File (.cst)');
  lines.push('// Generated by MultiHD Launcher');
  if (device) lines.push('// Device: ' + device);
  lines.push('//');
  lines.push('// Replace the placeholder pin numbers (XX) with actual LOC values');
  lines.push('// from your board\'s schematic / pin map.');
  lines.push('// Reference: Gowin EDA User Guide — Physical Constraints');
  lines.push('');

  if (ports.length === 0) {
    lines.push('// No ports auto-detected — add constraints manually:');
    lines.push('//');
    lines.push('// IO_LOC  "port_name" XX ;');
    lines.push('// IO_PORT "port_name" PULL_MODE=UP DRIVE=8 IOSTD=LVCMOS33 ;');
    return lines.join('\n') + '\n';
  }

  const emitGroup = (direction: CstPort['direction'], comment: string): void => {
    if (!ports.some((p) => p.direction === direction)) return;
    lines.push('// ── ' + comment + ' ──');
    for (const p of ports) {
      if (p.direction !== direction) continue;
      const widthPart = p.width ? ' ' + p.width : '';
      lines.push('IO_LOC  "' + p.name + '"' + widthPart + '  XX ;');
      lines.push('IO_PORT "' + p.name + '"  PULL_MODE=NONE  DRIVE=8  IOSTD=LVCMOS33 ;');
    }
    lines.push('');
  };

  emitGroup('input', 'Inputs');
  emitGroup('output', 'Outputs');
  emitGroup('inout', 'Bidirectional');

  return lines.join('\n') + '\n';
}

/**
 * Pure builder for `<project>.f` and `<project>.gprj` (+ the `.cst` pass-through)
 * exactly as `MainWindow::generateGowinFiles` writes them (mainwindow.cpp:798-842).
 */
export function buildGowinContents(
  o: GowinOptions,
): { cst: string; f: string; gprj: string } {
  const projName = o.projectName || path.basename(o.dir);
  const timestamp = o.timestamp;

  // Device fallback (mainwindow.cpp:784-786).
  let device = o.device;
  let pn = o.pn;
  if (!device) {
    device = DEFAULT_GOWIN_DEVICE;
    pn = device;
  }

  // ── .f (mainwindow.cpp:798-816): non-tb first, then _tb.sv, `./`-prefixed.
  const fLines: string[] = [
    '// Gowin file list (.f)',
    '// Generated by MultiHD Launcher  ' + timestamp,
    '// Pass this to vlog/iverilog with  -f ' + projName + '.f',
    '',
    '+incdir+.',
    '',
  ];
  for (const sv of o.activeFiles) {
    if (!sv.endsWith('_tb.sv')) fLines.push('./' + sv);
  }
  for (const sv of o.activeFiles) {
    if (sv.endsWith('_tb.sv')) fLines.push('./' + sv);
  }
  fLines.push('');
  const f = fLines.join('\n');

  // ── .gprj (mainwindow.cpp:818-842): TopModule = QFileInfo(topSv).baseName().
  const topEntity = baseNameWithoutSuffix(o.topFile);
  const gprjLines: string[] = [
    '<?xml version="1.0" encoding="UTF-8"?>',
    '<!-- Gowin EDA project — generated by MultiHD Launcher  ' + timestamp + ' -->',
    '<Project>',
    '  <Template>FPGA</Template>',
    '  <Version>5</Version>',
    '  <Device name="' + device + '" pn="' + pn + '"/>',
    '  <FileList>',
  ];
  for (const sv of o.activeFiles) {
    gprjLines.push('    <File path="' + sv + '" type="file.sv" enable="true"/>');
  }
  gprjLines.push('    <File path="' + projName + '.cst" type="file.cst" enable="true"/>');
  gprjLines.push('  </FileList>');
  gprjLines.push('  <Synthesis>');
  gprjLines.push('    <TopModule>' + topEntity + '</TopModule>');
  gprjLines.push('  </Synthesis>');
  gprjLines.push('</Project>');
  gprjLines.push('');
  const gprj = gprjLines.join('\n');

  return { cst: o.cstContent, f, gprj };
}

/**
 * Write `<dir>/<project>.cst`, `.f`, `.gprj` and create `impl/pnr/`
 * (mainwindow.cpp:788-846). All three files are always overwritten, exactly
 * like the Qt app; the `.cst` body is the editor content passed in unchanged.
 */
export function generateGowinFiles(o: GowinOptions): GenerationResult {
  const projName = o.projectName || path.basename(o.dir);
  const { cst, f, gprj } = buildGowinContents(o);

  const written: GeneratedFile[] = [];
  const skipped: Array<{ path: string; reason: string }> = [];
  const dirs: string[] = [];
  const warnings: string[] = [];

  ensureDir(o.dir);

  const cstPath = path.join(o.dir, projName + '.cst');
  writeTextFile(cstPath, cst);
  written.push({ path: cstPath, content: cst });

  const fPath = path.join(o.dir, projName + '.f');
  writeTextFile(fPath, f);
  written.push({ path: fPath, content: f });

  const gprjPath = path.join(o.dir, projName + '.gprj');
  writeTextFile(gprjPath, gprj);
  written.push({ path: gprjPath, content: gprj });

  const implDir = path.join(o.dir, 'impl', 'pnr');
  ensureDir(implDir);
  dirs.push(implDir);

  if (o.activeFiles.length === 0) {
    warnings.push('No active .sv files — generated Gowin project has no source files.');
  }
  if (o.cstContent === '' && !pathExists(cstPath)) {
    warnings.push('No CST content supplied — empty .cst file written.');
  }

  return { written, skipped, dirs, warnings };
}
